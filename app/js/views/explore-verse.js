/**
 * 這一張翻開之後的那一句。
 *   cardId：明信片 id（p1…）；r：cardRule(…) 或 cardOrigin(…)，要有 style，festival 可有可無
 *   回傳：{ text, by（作者，自己寫的是 ''）, title（篇名） }；沒有款式是 null
 */
function verseOf(cardId, r) {
  if (!r || !r.style) return null;
  const fest = r.festival ? r.festival.key : '';
  const keys = !fest ? [r.style.key] : r.style.gold ? ['gold+' + fest, fest] : [fest];
  const own = Object.prototype.hasOwnProperty.call(VERSES, cardId) ? VERSES[cardId] : null;
  let v = null;
  [own, VERSES._].some(function (row) {
    return !!row && keys.some(function (k) { v = row[k] || null; return !!v; });
  });
  if (!v) return null;
  return typeof v === 'string' ? { text: v, by: '', title: '' } : { text: v[0], by: v[1] || '', title: v[2] || '' };
}

/**
 * 那一句排成題字：逢逗號、句號斷行，一個短句一行（明信片頁與 /unlock 共用）。
 *   回傳：[{ t（字）, p（句尾標點，畫面上懸在行外） }]；每一行的 t＋p 接起來就是原句，字不增不減
 */
function verseLines(text) {
  const s = String(text || '');
  return (s.match(/[^，；。！？]+[，；。！？]*/g) || [s]).map(function (l) {
    const m = l.match(/^([\s\S]*?)([，；。！？]*)$/);
    return { t: m[1], p: m[2] };
  });
}

APP.explore = Object.assign(APP.explore, {
  VERSES: VERSES,
  VERSE_MAX: VERSE_MAX,
  verseOf: verseOf,
  verseLines: verseLines,
});

